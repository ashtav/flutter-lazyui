/// Defines the shape of the light focus used in the trainer widget.
///
/// - [circle]: A circular light focus.
/// - [rRect]: A rounded rectangle light focus.
enum ShapeLightFocus { circle, rRect }

/// Specifies the alignment of the content relative to the focus area.
///
/// - [top]: Content is aligned above the focus area.
/// - [bottom]: Content is aligned below the focus area.
/// - [left]: Content is aligned to the left of the focus area.
/// - [right]: Content is aligned to the right of the focus area.
enum ContentAlign { top, bottom, left, right }
