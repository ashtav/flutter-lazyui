import 'dart:io';

import 'package:lazyui/src/utilities/print.dart';

void main(List<String> args) {
  if (args.isEmpty) {
    String filename = 'lz.bat';
    String content = '''
@REM This file was generated by Lazyui, do not change it!
@REM Use: .\\lz <command>

@echo off
dart run lazyui:%*
''';

    // write the content to the .bat file
    File file = File(filename);
    file.writeAsStringSync(content);

    Print.info('Short command is activated, type .\\lz create <filename>');
    return;
  }

  final value = args[0].trim();

  if (value == '-v' || value == '--version') {
    Print.info('lazyui: 1.0.0');
  }
}
